// Command emoji-table generates the table of fully-qualified emoji that the content module
// normalizes emoji reactions with (ADR-0052 §1), from the emoji-test.txt of a Unicode version.
// `scripts/task.sh go:emoji-table` downloads the file, checks its digest, and runs it:
//
//	go run ./scripts/emoji-table -in emoji-test.txt -version 18.0.0 -out internal/domain/content/emoji_table.gen.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "", "the emoji-test.txt to read")
	out := flag.String("out", "", "the Go file to write")
	version := flag.String("version", "", "the Unicode version of the input, recorded in the output")
	flag.Parse()
	if *in == "" || *out == "" || *version == "" {
		log.Fatal("emoji-table: -in, -out, and -version are required")
	}
	src, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	var seqs []string
	sc := bufio.NewScanner(bytes.NewReader(src))
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") || strings.TrimSpace(line) == "" {
			continue
		}
		points, rest, ok := strings.Cut(line, ";")
		if !ok {
			log.Fatalf("emoji-table: malformed line %q", line)
		}
		status, _, _ := strings.Cut(rest, "#")
		if strings.TrimSpace(status) != "fully-qualified" {
			continue
		}
		seqs = append(seqs, strings.Join(strings.Fields(points), " "))
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(seqs) == 0 {
		log.Fatal("emoji-table: no fully-qualified emoji in the input")
	}
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: AGPL-3.0-only\n\n")
	fmt.Fprintf(&b, "// Code generated by scripts/emoji-table from the emoji-test.txt of Unicode %s; DO NOT EDIT.\n\n", *version)
	b.WriteString("package content\n\n")
	fmt.Fprintf(&b, "// EmojiVersion is the Unicode version of the emoji that emoji reactions accept.\nconst EmojiVersion = %q\n\n", *version)
	b.WriteString("// fullyQualifiedEmoji lists the fully-qualified emoji, one per line, as hexadecimal code points.\n")
	b.WriteString("const fullyQualifiedEmoji = `")
	b.WriteString(strings.Join(seqs, "\n"))
	b.WriteString("`\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o600); err != nil {
		log.Fatal(err)
	}
}
