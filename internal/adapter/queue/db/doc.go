// Package db implements the job queue ports on the application database (ADR-0004), for both
// SQLite (internal/adapter/db/sqlite) and PostgreSQL (internal/adapter/db/postgres).
//
// Queue keeps jobs in the jobs table and implements queue.JobQueue, queue.Outbox (it inserts
// into jobs in the caller's transaction, so no relay is needed), queue.Source for
// queue.PullRunner, and queue.DeadJobs. Claims are leases recorded in jobs.locked_by and
// jobs.locked_until: a worker that stops while running a job leaves the lease to expire, and
// another worker claims the job again.
//
//   - PostgreSQL claims with FOR UPDATE SKIP LOCKED, so any number of workers can share the
//     queue without waiting on each other.
//   - SQLite serializes every write transaction (BEGIN IMMEDIATE), so claims never collide; run
//     a single worker per database, since more workers only contend for the same lock.
//
// Outbox keeps jobs in outbox_events for a queue outside the database (SQS, Cloud Tasks):
// EnqueueTx writes them in the domain transaction and Relay moves them into that queue.
//
// The queries are generated by sqlc from queries/<dialect>/queue (see sqlc.yaml).
package db
